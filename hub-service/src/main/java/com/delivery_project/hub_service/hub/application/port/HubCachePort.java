package com.delivery_project.hub_service.hub.application.port;

/**
 * 허브 캐시 무효화 포트.
 *
 * <p>Command Service 는 "무효화한다" 는 의도만 알고 그것이 Spring Cache 인지 Redis 인지는 모른다.
 * 구현은 {@code hub/infrastructure/adapter/HubCacheAdapter} 가 맡는다.
 *
 * <p><b>두 메서드 모두 DB 커밋 이후에 실제 무효화가 일어난다.</b> 호출자는 트랜잭션 안에서 부르면
 * 되고 시점을 신경 쓰지 않아도 된다. 커밋 전에 지우면 그 사이 조회가 옛 값을 다시 캐시에 올리고,
 * 롤백되면 멀쩡한 캐시만 날린 꼴이 되기 때문이다.
 *
 * <p><b>캐시 장애는 호출자에게 전파되지 않는다.</b> 캐시는 성능 장치일 뿐이고, 하필 커밋 이후라
 * 실패를 알려도 되돌릴 수 없다.
 */
public interface HubCachePort {

	/**
	 * 허브 단건 캐시 전체를 비운다. 허브 수정·삭제 시 호출한다.
	 *
	 * <p>바뀐 허브의 키 하나만 지워서는 부족하다. {@code HubDetailResult} 는 상위 허브에서 복사해 온
	 * {@code parentHubName} 을 함께 담기 때문에, 중앙 허브의 이름이 바뀌면 그 값을 품고 있는
	 * <b>하위 허브들의 캐시</b>까지 낡는다. 어떤 키가 영향받는지는 캐시 키만 봐서는 알 수 없다.
	 *
	 * <p>그래서 통째로 비운다. <b>허브는 17개로 고정이고 수정이 사실상 없어</b> 다시 채우는 비용이
	 * 무시할 만하다.
	 */
	void evictAllHubs();

	/**
	 * 산출된 경로 캐시 전체를 비운다. 허브·이동정보 변경 시 호출한다.
	 *
	 * <p>키 하나만 지울 수 없다 — 허브나 구간 하나가 바뀌면 그것을 지나는 모든 (출발, 도착) 쌍의
	 * 경로가 함께 틀어지고, 어떤 쌍이 영향받는지는 캐시 키만 봐서 알 수 없기 때문이다.
	 * 경로 캐시는 TTL 이 1시간이라 통째로 비워도 다시 채우는 비용이 크지 않다.
	 */
	void evictAllHubPaths();
}
